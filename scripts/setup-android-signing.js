const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const rootDir = path.resolve(__dirname, '..');
const androidDir = path.join(rootDir, 'android');
const keystorePath = path.join(androidDir, 'zyrun-release.keystore');
const propsPath = path.join(androidDir, 'keystore.properties');
const examplePath = path.join(androidDir, 'keystore.example.properties');

const alias = process.env.ZYRUN_RELEASE_KEY_ALIAS || 'zyrun-release';
const password = process.env.ZYRUN_RELEASE_STORE_PASSWORD || 'changeit';
const keyPassword = process.env.ZYRUN_RELEASE_KEY_PASSWORD || password;

if (!fs.existsSync(androidDir)) {
  fs.mkdirSync(androidDir, { recursive: true });
}

if (fs.existsSync(keystorePath)) {
  console.log(`Using existing keystore: ${keystorePath}`);
} else {
  const keytool = process.env.JAVA_HOME ? path.join(process.env.JAVA_HOME, 'bin', 'keytool') : 'keytool';
  execFileSync(keytool, [
    '-genkeypair',
    '-v',
    '-keystore', keystorePath,
    '-alias', alias,
    '-keyalg', 'RSA',
    '-keysize', '2048',
    '-validity', '10000',
    '-storepass', password,
    '-keypass', keyPassword,
    '-dname', 'CN=Zy-Run Release, OU=Android, O=Zy-Run, L=Unknown, S=Unknown, C=US',
  ], { stdio: 'inherit' });
  console.log(`Created new keystore: ${keystorePath}`);
}

const props = [
  '# Generated by scripts/setup-android-signing.js',
  '# Keep this file out of source control. It is intentionally ignored by git.',
  `releaseStoreFile=./zyrun-release.keystore`,
  `releaseStorePassword=${password}`,
  `releaseKeyAlias=${alias}`,
  `releaseKeyPassword=${keyPassword}`,
].join('\n');

fs.writeFileSync(propsPath, `${props}\n`);
console.log(`Saved Android signing config to: ${propsPath}`);

if (!fs.existsSync(examplePath)) {
  fs.copyFileSync(path.join(rootDir, 'android', 'keystore.example.properties'), examplePath);
}

console.log('Use the same keystore for every daily APK build to keep Google consent stable.');
